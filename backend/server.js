// ================================================

app.post("/api/bookings", async (req, res) => {

    try {

        const {
            name,
            email,
            destination,
            hotel_name,
            nights,
            message
        } = req.body || {};

        if (
            typeof name !== "string" ||
            typeof email !== "string" ||
            typeof destination !== "string" ||
            typeof hotel_name !== "string" ||
            !name.trim() ||
            !email.trim() ||
            !destination.trim() ||
            !hotel_name.trim()
        ) {

            return res.status(400).json({
                success: false,
                message: "Please fill all required fields."
            });
        }

        const emailPattern = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;

        if (!emailPattern.test(email.trim())) {

            return res.status(400).json({
                success: false,
                message: "Please enter a valid email address."
            });
        }

        const numberOfNights = Number(nights);

        if (
            !Number.isInteger(numberOfNights) ||
            numberOfNights < 1 ||
            numberOfNights > 365
        ) {

            return res.status(400).json({
                success: false,
                message: "Please enter between 1 and 365 nights."
            });
        }

        // Find hotel and get its actual database price.

        const hotelResult = await pool.query(`
            SELECT
                hotel_name,
                destination,
                price_per_night
            FROM destination_hotels
            WHERE LOWER(destination) = LOWER($1)
              AND LOWER(hotel_name) = LOWER($2)
              AND price_per_night > 0
            LIMIT 1
        `, [
            destination.trim(),
            hotel_name.trim()
        ]);

        if (hotelResult.rows.length === 0) {

            return res.status(400).json({
                success: false,
                message: "Hotel not found or price unavailable."
            });
        }

        const hotel = hotelResult.rows[0];

        const hotelPrice = Number(hotel.price_per_night);

        const amount = hotelPrice * numberOfNights;

        if (!Number.isFinite(amount) || amount <= 0) {

            return res.status(400).json({
                success: false,
                message: "Invalid booking amount."
            });
        }

        const result = await pool.query(`
            INSERT INTO bookings (
                name,
                email,
                destination,
                hotel_name,
                hotel_price,
                nights,
                amount,
                message,
                status,
                payment_status
            )
            VALUES (
                $1, $2, $3, $4, $5, $6, $7, $8,
                'Pending', 'Pending'
            )
            RETURNING id
        `, [
            name.trim(),
            email.trim(),
            hotel.destination,
            hotel.hotel_name,
            hotelPrice,
            numberOfNights,
            amount,
            typeof message === "string"
                ? message.trim()
                : ""
        ]);

        res.status(201).json({
            success: true,
            message: "Booking successful.",
            bookingId: Number(result.rows[0].id),
            destination: hotel.destination,
            hotelName: hotel.hotel_name,
            hotelPrice,
            nights: numberOfNights,
            amount,
            paymentStatus: "Pending"
        });

    } catch (error) {

        console.error("Booking error:", error);

        res.status(500).json({
            success: false,
            message: "Booking failed. Please try again."
        });
    }
});

