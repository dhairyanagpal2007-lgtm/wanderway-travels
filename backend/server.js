app.get("/api/hotels", async (req, res) => {

    const destination =
        typeof req.query.destination === "string"
            ? req.query.destination.trim()
            : "";

    if (!destination) {

        return res.status(400).json({
            success: false,
            message: "Please select a destination."
        });
    }

    const allDestinations = [
        ...indianDestinations,
        ...unionTerritories,
        ...internationalDestinations
    ];

    const validDestination = allDestinations.some(
        item =>
            typeof item === "string" &&
            item.toLowerCase() === destination.toLowerCase()
    );

    if (!validDestination) {

        return res.status(400).json({
            success: false,
            message: "Invalid destination selected."
        });
    }

    try {

        const result = await pool.query(`
            SELECT
                id,
                destination,
                hotel_name,
                price_per_night,
                price_per_night AS price,
                price_per_night AS hotel_price,
                description,
                image_url,
                gallery_images,
                fallback_image_url,
                facilities
            FROM destination_hotels
            WHERE LOWER(destination) = LOWER($1)
            ORDER BY hotel_name ASC
            LIMIT $2
        `, [
            destination,
            MAX_HOTELS_PER_DESTINATION
        ]);

        const hotels = result.rows.map(hotel => {

            return {
                ...hotel,

                gallery_images: parseArray(
                    hotel.gallery_images
                ),

                facilities: parseArray(
                    hotel.facilities
                )
            };
        });

        res.json({
            success: true,
            destination,
            count: hotels.length,
            maximumHotels: MAX_HOTELS_PER_DESTINATION,
            hotels
        });

    } catch (error) {

        console.error("Hotel loading error:", error);

        res.status(500).json({
            success: false,
            message: "Unable to load hotels."
        });
    }
});

