app.get("/api/bookings", requireAdmin, async (req, res) => {
    try {
        const bookingResult = await pool.query(`
            SELECT * FROM bookings
            ORDER BY id DESC
        `);

        const bookings = bookingResult.rows;

        if (bookings.length === 0) {
            return res.json([]);
        }

        const bookingIds = bookings.map(booking => booking.id);

        const roomResult = await pool.query(`
            SELECT
                id,
                booking_id,
                room_number,
                guests_count
            FROM booking_rooms
            WHERE booking_id = ANY($1::bigint[])
            ORDER BY booking_id, room_number
        `, [bookingIds]);

        const roomIds = roomResult.rows.map(room => room.id);

        let guestRows = [];

        if (roomIds.length > 0) {
            const guestResult = await pool.query(`
                SELECT
                    id,
                    room_id,
                    guest_name,
                    age,
                    guest_mobile,
                    guest_email,
                    aadhaar_last4,
                    pan_last4
                FROM booking_guests
                WHERE room_id = ANY($1::bigint[])
                ORDER BY id
            `, [roomIds]);

            guestRows = guestResult.rows;
        }

        const guestsByRoom = new Map();

        for (const guest of guestRows) {
            const key = String(guest.room_id);

            if (!guestsByRoom.has(key)) {
                guestsByRoom.set(key, []);
            }

            guestsByRoom.get(key).push({
                id: Number(guest.id),
                name: guest.guest_name,
                age: guest.age,
                mobile: guest.guest_mobile,
                email: guest.guest_email,
                aadhaar_last4: guest.aadhaar_last4,
                pan_last4: guest.pan_last4
            });
        }

        const roomsByBooking = new Map();

        for (const room of roomResult.rows) {
            const key = String(room.booking_id);

            if (!roomsByBooking.has(key)) {
                roomsByBooking.set(key, []);
            }

            roomsByBooking.get(key).push({
                roomNumber: room.room_number,
                guestsCount: room.guests_count,
                guests: guestsByRoom.get(String(room.id)) || []
            });
        }

        res.json(bookings.map(booking => {
            const rooms =
                roomsByBooking.get(String(booking.id)) || [];

            return {
                ...booking,
                rooms,
                total_guests: rooms.reduce(
                    (sum, room) => sum + room.guests.length,
                    0
                )
            };
        }));

    } catch (error) {
        console.error("Booking loading error:", error);

        res.status(500).json({
            success: false,
            message: "Could not load bookings."
        });
    }
});

