async function initializeDatabase() {

    // BOOKINGS TABLE

    await pool.query(`
        CREATE TABLE IF NOT EXISTS bookings (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name TEXT NOT NULL DEFAULT '',
            email TEXT NOT NULL DEFAULT '',
            destination TEXT DEFAULT '',
            hotel_name TEXT DEFAULT '',
            check_in_date DATE,
            check_out_date DATE,
            hotel_price DOUBLE PRECISION DEFAULT 0,
            nights INTEGER DEFAULT 1,
            amount DOUBLE PRECISION DEFAULT 0,
            message TEXT DEFAULT '',
            status TEXT DEFAULT 'Pending',
            payment_status TEXT DEFAULT 'Pending',
            created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
        )
    `);

    // ADD MISSING COLUMNS TO EXISTING BOOKINGS TABLE

    const requiredColumns = [
        ["name", "TEXT DEFAULT ''"],
        ["email", "TEXT DEFAULT ''"],
        ["destination", "TEXT DEFAULT ''"],
        ["hotel_name", "TEXT DEFAULT ''"],
        ["check_in_date", "DATE"],
        ["check_out_date", "DATE"],
        ["hotel_price", "DOUBLE PRECISION DEFAULT 0"],
        ["nights", "INTEGER DEFAULT 1"],
        ["amount", "DOUBLE PRECISION DEFAULT 0"],
        ["message", "TEXT DEFAULT ''"],
        ["status", "TEXT DEFAULT 'Pending'"],
        ["payment_status", "TEXT DEFAULT 'Pending'"],
        ["created_at", "TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP"]
    ];

    for (const [column, definition] of requiredColumns) {
        await pool.query(`
            ALTER TABLE bookings
            ADD COLUMN IF NOT EXISTS ${column} ${definition}
        `);
    }

    await pool.query(`
        UPDATE bookings
        SET created_at = CURRENT_TIMESTAMP
        WHERE created_at IS NULL
    `);

    // ROOM TABLE

    await pool.query(`
        CREATE TABLE IF NOT EXISTS booking_rooms (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            booking_id BIGINT NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
            room_number INTEGER NOT NULL,
            guests_count INTEGER NOT NULL CHECK (guests_count BETWEEN 1 AND 5),
            UNIQUE (booking_id, room_number)
        )
    `);

    // GUEST TABLE

    await pool.query(`
        CREATE TABLE IF NOT EXISTS booking_guests (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            room_id BIGINT NOT NULL REFERENCES booking_rooms(id) ON DELETE CASCADE,
            guest_name TEXT NOT NULL,
            age INTEGER CHECK (age IS NULL OR age BETWEEN 0 AND 120),
            guest_mobile VARCHAR(20),
            guest_email VARCHAR(254),
            aadhaar_last4 VARCHAR(4),
            pan_last4 VARCHAR(4)
        )
    `);

    // SAFE ADDITIVE MIGRATIONS FOR EXISTING GUEST TABLE

    const guestColumns = [
        ["age", "INTEGER"],
        ["guest_mobile", "VARCHAR(20)"],
        ["guest_email", "VARCHAR(254)"],
        ["aadhaar_last4", "VARCHAR(4)"],
        ["pan_last4", "VARCHAR(4)"]
    ];

    for (const [column, definition] of guestColumns) {
        await pool.query(`
            ALTER TABLE booking_guests
            ADD COLUMN IF NOT EXISTS ${column} ${definition}
        `);
    }

    // INDEXES

    await pool.query(`
        CREATE INDEX IF NOT EXISTS idx_booking_rooms_booking_id
        ON booking_rooms (booking_id)
    `);

    await pool.query(`
        CREATE INDEX IF NOT EXISTS idx_booking_guests_room_id
        ON booking_guests (room_id)
    `);

    console.log("Bookings, rooms and guests tables ready.");

    // HOTEL TABLE

    await pool.query(`
        CREATE TABLE IF NOT EXISTS destination_hotels (
            id TEXT PRIMARY KEY,
            destination TEXT NOT NULL,
            region_type TEXT NOT NULL,
            hotel_name TEXT NOT NULL,
            price_per_night DOUBLE PRECISION NOT NULL,
            description TEXT DEFAULT '',
            image_url TEXT DEFAULT '',
            gallery_images TEXT DEFAULT '[]',
            facilities TEXT DEFAULT '[]',
            fallback_image_url TEXT DEFAULT ''
        )
    `);

    const hotelCount = await pool.query(`
        SELECT COUNT(*) AS total
        FROM destination_hotels
    `);

    const existingHotels = Number(hotelCount.rows[0].total);

    if (existingHotels === 0) {
        console.log("Creating hotel catalogue...");
        await initializeDestinationHotels(pool);
    } else {
        console.log(
            "Existing hotel catalogue found:",
            existingHotels
        );
        console.log("Keeping existing hotel catalogue.");
    }

    // INDEXES

    await pool.query(`
        CREATE INDEX IF NOT EXISTS
        idx_hotels_destination
        ON destination_hotels (destination)
    `);

    await pool.query(`
        CREATE INDEX IF NOT EXISTS
        idx_bookings_created_at
        ON bookings (created_at DESC)
    `);

    const result = await pool.query(`
        SELECT
            COUNT(*) AS total,
            COUNT(*) FILTER (
                WHERE price_per_night > 0
            ) AS valid_prices
        FROM destination_hotels
    `);

    console.log("Total hotels:", result.rows[0].total);
    console.log("Hotels with valid prices:", result.rows[0].valid_prices);
}

